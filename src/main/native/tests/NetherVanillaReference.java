import com.google.gson.JsonElement;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import java.io.InputStreamReader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import net.minecraft.SharedConstants;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.registries.VanillaRegistries;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.levelgen.NoiseRouter;
import net.minecraft.world.level.levelgen.RandomState;
import net.minecraft.world.level.levelgen.densityfunction.DensityFunctions;
import net.minecraft.world.level.levelgen.densityfunction.DensitySampler;
import net.minecraft.world.level.levelgen.densityfunction.SamplerContext;

/** Offline 26.3 oracle: executes vanilla classes, without generating a world/chunk. */
public final class NetherVanillaReference {
    private static JsonElement read(String resource) throws Exception {
        try (var reader = new InputStreamReader(NetherVanillaReference.class.getResourceAsStream(resource))) {
            return JsonParser.parseReader(reader);
        }
    }

    private static JsonElement inlineBase(JsonElement value, JsonElement base) {
        if (value.isJsonPrimitive() && value.getAsJsonPrimitive().isString()
                && value.getAsString().equals("minecraft:nether/base_3d_noise")) return base;
        if (value.isJsonObject()) {
            var object = value.getAsJsonObject();
            for (String key : object.keySet().toArray(String[]::new)) {
                object.add(key, inlineBase(object.get(key), base));
            }
        }
        return value;
    }

    private static float sample(DensitySampler sampler, int x, int y, int z) {
        return sampler.sampleValue(SamplerContext.EMPTY_UNCACHED, x, y, z);
    }

    private static int floor(DensitySampler sampler, int x, int y, int z) {
        while (y > 0 && sample(sampler, x, y, z) > 0) --y;
        while (y > 0 && sample(sampler, x, y, z) <= 0) --y;
        return y;
    }

    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        if (!SharedConstants.getCurrentVersion().name().equals("26.3")) {
            throw new IllegalStateException("Reference requires Minecraft 26.3");
        }
        var baseJson = read("/data/minecraft/worldgen/density_function/nether/base_3d_noise.json");
        var settings = read("/data/minecraft/worldgen/noise_settings/nether.json").getAsJsonObject();
        if (!settings.get("legacy_random_source").getAsBoolean()) throw new AssertionError("legacy random");
        var base = DensityFunctions.DIRECT_CODEC.parse(JsonOps.INSTANCE, baseJson).getOrThrow();
        var density = DensityFunctions.DIRECT_CODEC.parse(JsonOps.INSTANCE, inlineBase(
                settings.getAsJsonObject("noise_router").get("final_density"), baseJson)).getOrThrow();
        var noises = VanillaRegistries.createWorldLookup().lookupOrThrow(Registries.NOISE);
        var zero = DensityFunctions.zero();
        // Only final_density is sampled; climate/material fields do not affect it.
        var router = new NoiseRouter(zero, zero, zero, zero, zero, zero, zero, density);
        long[] seeds = {0, -1, 8371904829L, 2842062689604764280L};
        int[][] positions = {{0, 0}, {-170, 14}, {172, -20}, {-1023, -65},
                {12345, 6789}, {-8000, 12000}, {-49, -17}, {-170, -18}};
        var output = new StringBuilder("/* Generated by NetherVanillaReference using Minecraft 26.3 classes. */\n");
        output.append("static const struct {\n    int64_t seed; int x, z;\n")
                .append("    double base[17], density[17]; int floor64, floor100, floor127;\n")
                .append("} nether_vanilla[] = {\n");
        for (long seed : seeds) {
            var state = RandomState.create(noises, seed, true, Blocks.NETHERRACK.defaultBlockState(),
                    settings.get("sea_level").getAsInt(), router);
            var baseSampler = state.getSampler(base);
            var densitySampler = state.getSampler(density);
            for (int[] position : positions) {
                int x = position[0], z = position[1];
                output.append(String.format(Locale.ROOT, "    {INT64_C(%d), %d, %d,\n        {", seed, x, z));
                for (int i = 0; i <= 16; ++i) {
                    if (i != 0) output.append(", ");
                    output.append(Float.toString(sample(baseSampler, Math.floorDiv(x, 4) * 4, i * 8,
                            Math.floorDiv(z, 4) * 4)));
                }
                output.append("},\n        {");
                for (int i = 0; i <= 16; ++i) {
                    if (i != 0) output.append(", ");
                    output.append(Float.toString(sample(densitySampler, x, Math.min(i * 8, 127), z)));
                }
                output.append(String.format(Locale.ROOT, "}, %d, %d, %d},\n",
                        floor(densitySampler, x, 64, z), floor(densitySampler, x, 100, z),
                        floor(densitySampler, x, 127, z)));
            }
        }
        output.append("};\n");
        Files.writeString(Path.of(args[0]), output);
        int columns = seeds.length * positions.length;
        System.out.printf("Wrote %d columns: %d base values, %d final densities, %d cave floors%n",
                columns, columns * 17, columns * 17, columns * 3);
    }
}
